export const getRecipeById = (id: string): Recipe | undefined =>
  recipes.find((r) => r.id === id);

export const getRelatedRecipes = (recipe: Recipe, count = 4): Recipe[] =>
  recipes
    .filter((r) => r.id !== recipe.id)
    .map((r) => {
      let score = 0;
      if (r.category === recipe.category) score += 3;
      if (r.mealType === recipe.mealType) score += 2;
      const sharedIngredients = r.ingredients.filter((ri) =>
        recipe.ingredients.some((i) => i.name === ri.name)
      ).length;
      score += sharedIngredients;
      return { recipe: r, score };
    })
    .sort((a, b) => b.score - a.score)
    .slice(0, count)
    .map((x) => x.recipe);
